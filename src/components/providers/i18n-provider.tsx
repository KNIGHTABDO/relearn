"use client";

import React, { createContext, useContext, useState, useEffect, useCallback } from "react";

export type Language = "en" | "es" | "fr" | "ar" | "de" | "zh" | "ja" | "ko" | "pt" | "hi";

interface I18nContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  dir: "ltr" | "rtl";
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function useTranslation() {
  return useI18n();
}

// RTL support disabled until proper RTL layout is implemented
const RTL_LANGUAGES: Language[] = [];

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>("en");

  useEffect(() => {
    const saved = localStorage.getItem("relearn-language") as Language | null;
    if (saved) setLangState(saved);
  }, []);

  const setLang = useCallback((newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem("relearn-language", newLang);
    document.documentElement.lang = newLang;
    // dir setting disabled — RTL layout not ready
    // document.documentElement.dir = RTL_LANGUAGES.includes(newLang) ? "rtl" : "ltr";
    window.dispatchEvent(new CustomEvent("language-changed", { detail: newLang }));
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    // document.documentElement.dir = RTL_LANGUAGES.includes(lang) ? "rtl" : "ltr";
  }, [lang]);

  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    const translations = getTranslations(lang);
    let text = translations[key] || getTranslations("en")[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp("\\{" + k + "\\}", "g"), String(v));
      });
    }
    return text;
  }, [lang]);

  const dir = RTL_LANGUAGES.includes(lang) ? "rtl" : "ltr";

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </I18nContext.Provider>
  );
}

// Translation loader
function getTranslations(lang: Language): Record<string, string> {
  return allTranslations[lang] || allTranslations.en;
}

// Get AI system prompt suffix for the current language
export function getAILanguagePrompt(lang: Language): string {
  if (lang === "en") return "";
  const names: Record<Language, string> = {
    en: "English", es: "Spanish", fr: "French", ar: "Arabic",
    de: "German", zh: "Chinese", ja: "Japanese", ko: "Korean",
    pt: "Portuguese", hi: "Hindi",
  };
  return "\nIMPORTANT: Respond entirely in " + names[lang] + ". All explanations, quiz questions, flashcards, summaries, and chat responses must be in " + names[lang] + ".";
}

